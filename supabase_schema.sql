-- ====================================================================
-- VibeCart AI - Supabase PostgreSQL Database Schema
-- Tables: owned_wardrobe, saved_boards, price_alerts
-- ====================================================================

-- Enable UUID extension if not already enabled
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";

-- --------------------------------------------------------------------
-- 1. Table: owned_wardrobe
-- Tracks user's owned clothing and accessories for conflict checking
-- --------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.owned_wardrobe (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id TEXT DEFAULT 'guest_user',
    name TEXT NOT NULL,
    category TEXT NOT NULL CHECK (category IN ('top', 'bottom', 'footwear', 'outerwear', 'accessory')),
    color TEXT NOT NULL,
    brand TEXT,
    style_tags TEXT[] DEFAULT ARRAY[]::TEXT[],
    estimated_cost NUMERIC(10, 2) DEFAULT 0.00,
    wears_count INTEGER DEFAULT 0,
    image_url TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- Index for user lookups
CREATE INDEX IF NOT EXISTS idx_owned_wardrobe_user ON public.owned_wardrobe(user_id);

-- --------------------------------------------------------------------
-- 2. Table: saved_boards
-- Stores curated 3-item capsule collections generated by Gemini AI
-- --------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.saved_boards (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id TEXT DEFAULT 'guest_user',
    title TEXT NOT NULL,
    scenario_prompt TEXT NOT NULL,
    vibe_summary TEXT,
    total_price NUMERIC(10, 2) NOT NULL DEFAULT 0.00,
    items JSONB NOT NULL DEFAULT '[]'::JSONB,
    aesthetic_tags TEXT[] DEFAULT ARRAY[]::TEXT[],
    is_public BOOLEAN DEFAULT false,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_saved_boards_user ON public.saved_boards(user_id);

-- --------------------------------------------------------------------
-- 3. Table: price_alerts
-- Tracks items for price drops with Guardrailed 1-tap Auto-Buy triggers
-- --------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.price_alerts (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id TEXT DEFAULT 'guest_user',
    product_title TEXT NOT NULL,
    category TEXT,
    store_platform TEXT NOT NULL CHECK (store_platform IN ('Amazon', 'Flipkart', 'Myntra', 'Other')),
    product_url TEXT NOT NULL,
    image_url TEXT,
    current_price NUMERIC(10, 2) NOT NULL,
    target_price NUMERIC(10, 2) NOT NULL,
    auto_buy_enabled BOOLEAN DEFAULT false,
    spend_cap NUMERIC(10, 2) DEFAULT 8000.00,
    status TEXT DEFAULT 'watching' CHECK (status IN ('watching', 'target_hit', 'auto_ordered', 'paused')),
    last_checked_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()),
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_price_alerts_user ON public.price_alerts(user_id);

-- --------------------------------------------------------------------
-- Row Level Security (RLS) Policies
-- --------------------------------------------------------------------
ALTER TABLE public.owned_wardrobe ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.saved_boards ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.price_alerts ENABLE ROW LEVEL SECURITY;

-- Allow anonymous & authenticated users full access for development & guest mode
CREATE POLICY "Allow public read owned_wardrobe" ON public.owned_wardrobe FOR SELECT USING (true);
CREATE POLICY "Allow public insert owned_wardrobe" ON public.owned_wardrobe FOR INSERT WITH CHECK (true);
CREATE POLICY "Allow public update owned_wardrobe" ON public.owned_wardrobe FOR UPDATE USING (true);
CREATE POLICY "Allow public delete owned_wardrobe" ON public.owned_wardrobe FOR DELETE USING (true);

CREATE POLICY "Allow public read saved_boards" ON public.saved_boards FOR SELECT USING (true);
CREATE POLICY "Allow public insert saved_boards" ON public.saved_boards FOR INSERT WITH CHECK (true);
CREATE POLICY "Allow public delete saved_boards" ON public.saved_boards FOR DELETE USING (true);

CREATE POLICY "Allow public read price_alerts" ON public.price_alerts FOR SELECT USING (true);
CREATE POLICY "Allow public insert price_alerts" ON public.price_alerts FOR INSERT WITH CHECK (true);
CREATE POLICY "Allow public update price_alerts" ON public.price_alerts FOR UPDATE USING (true);
CREATE POLICY "Allow public delete price_alerts" ON public.price_alerts FOR DELETE USING (true);

